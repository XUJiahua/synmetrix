package cmd

import (
	"os"

	"github.com/spf13/cobra"
)

// rootCmd represents the base command when called without any subcommands
var rootCmd = &cobra.Command{
	Use:   "go-actions",
	Short: "Keycloak JIT user sync service for Synmetrix",
	Long: `go-actions is a service that handles just-in-time user synchronization
between Keycloak and Hasura for the Synmetrix platform.

It provides a HTTP server that responds to Hasura Actions, automatically
creating users in the Hasura database when they first log in via Keycloak.`,
}

// Execute adds all child commands to the root command and sets flags appropriately.
// This is called by main.main(). It only needs to happen once to the rootCmd.
func Execute() {
	err := rootCmd.Execute()
	if err != nil {
		os.Exit(1)
	}
}

